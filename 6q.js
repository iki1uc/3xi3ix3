// NC.engine — re-finalisierte iki1uc-Version
// ======================================================

export const NC = {

  // ----------------------------------------------
  // 1) ORG — reine Achse
  // ----------------------------------------------
  ORG(x) {
    return x;
  },

  // ----------------------------------------------
  // 2) REORG — geregelte Achse
  // ----------------------------------------------
  REORG(x) {
    return x * 0.33;
  },

  // ----------------------------------------------
  // 3) NCORG — Tiefenachse
  // ----------------------------------------------
  NCORG(x) {
    return x * 0.81;
  },

  // ----------------------------------------------
  // 4) NC — Rohrschlosser (Tiefe)
  // ----------------------------------------------
  NC_ENGINE(x) {
    return {
      depth: this.NCORG(x),
      density: x * 0.81
    };
  },

  // ----------------------------------------------
  // 5) REORG_ENGINE — Ingenieur (Regelung)
  // ----------------------------------------------
  REORG_ENGINE(x) {
    return {
      regulated: this.REORG(x)
    };
  },

  // ----------------------------------------------
  // 6) ORG_ENGINE — Loop (Start)
  // ----------------------------------------------
  ORG_ENGINE(x) {
    return {
      raw: this.ORG(x)
    };
  }
};
